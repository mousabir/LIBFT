#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	const unsigned char	*st1;
	const unsigned char	*st2;
	size_t				i;

	st1 = (const unsigned char *)s1;
	st2 = (const unsigned char *)s2;
	i = 0;
	while (i < n && st1[i] == st2[i])
		i++;
	if (i == n)
		return (0);
	else
		return (st1[i] - st2[i]);
}
