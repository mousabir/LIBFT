#include <stddef.h>

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;
	size_t	j;
	size_t	m;

	i = 0;
	m = 0;
	while (little[m])
		m++;
	if (little[0] == '\0')
		return ((char *)big);
	while (big[i] && i <= len && m <= len - i)
	{
		j = 0;
		while (little[j] != '\0' && i + j < len && big[i + j] == little[j])
			j++;
		if (little[j] == '\0')
			return ((char *)&big[i]);
		i++;
	}
	return (NULL);
}
